commit() { git -C "$R" commit -q --allow-empty -m "$1" >/dev/null 2>&1; }
# A commit that prepares a scenario must succeed, or the assertions after it would silently
# check the previous commit instead
setup_commit() {
  local subject="${1%%$'\n'*}"
  if commit "$1" && [ "$(git -C "$R" log -1 --format=%s)" = "$subject" ]; then
    return 0
  fi
  fail "setup commit failed: $subject"
}
