guard() {
  local cmd="$1" json
  if command -v jq >/dev/null 2>&1; then
    json="$(jq -n --arg c "$cmd" --arg d "$R" '{tool_name:"Bash",tool_input:{command:$c},cwd:$d}')"
  else
    json="$(python3 -c 'import json,sys; print(json.dumps({"tool_name":"Bash","tool_input":{"command":sys.argv[1]},"cwd":sys.argv[2]}))' "$cmd" "$R")"
  fi
  printf '%s' "$json" | bash "$GUARD"
}
# A crash (non-zero exit) or malformed JSON must never pass as "allow"
decision() {
  local out rc
  out="$(guard "$1")"
  rc=$?
  if [ "$rc" -ne 0 ]; then echo "error: exit $rc"; return; fi
  if [ -n "$out" ] && ! printf '%s' "$out" | python3 -c 'import json, sys; json.load(sys.stdin)' 2>/dev/null; then
    echo "error: invalid JSON: $out"
    return
  fi
  case "$out" in
    *'"deny"'*) echo deny ;;
    *'"ask"'*) echo ask ;;
    '') echo allow ;;
    *) echo "unexpected: $out" ;;
  esac
}
expect() { check "$2 → $1" "[ \"\$(decision $(printf '%q' "$2"))\" = '$1' ]"; }

